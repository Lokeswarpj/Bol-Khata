-- 1. Store Owners (Merchants)
CREATE TABLE IF NOT EXISTS public.store_owners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name TEXT NOT NULL,
    owner_name TEXT NOT NULL,
    phone TEXT UNIQUE,
    pin TEXT DEFAULT '1234',
    address TEXT,
    language_preference TEXT DEFAULT 'en-IN',
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Customers (Debtors & Ledger Accounts)
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT REFERENCES public.store_owners(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    phone TEXT,
    nickname TEXT,
    opted_in_reminders BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Transactions (Udhaar Credit & Jama Payments)
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT REFERENCES public.store_owners(id) ON DELETE SET NULL,
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE CASCADE,
    amount NUMERIC NOT NULL,
    direction TEXT NOT NULL CHECK (direction IN ('credit', 'payment')),
    transaction_date DATE DEFAULT CURRENT_DATE,
    note TEXT,
    raw_transcript TEXT,
    corrected BOOLEAN DEFAULT FALSE,
    correction_of BIGINT REFERENCES public.transactions(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_customers_owner ON public.customers(owner_id);
CREATE INDEX IF NOT EXISTS idx_customers_name ON public.customers(name);
CREATE INDEX IF NOT EXISTS idx_transactions_owner ON public.transactions(owner_id);
CREATE INDEX IF NOT EXISTS idx_transactions_customer ON public.transactions(customer_id);
CREATE INDEX IF NOT EXISTS idx_transactions_date ON public.transactions(transaction_date);

-- Enable Row Level Security (RLS) & Grant Anon Access
ALTER TABLE public.store_owners ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow anon all on store_owners" ON public.store_owners;
CREATE POLICY "Allow anon all on store_owners" ON public.store_owners FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon all on customers" ON public.customers;
CREATE POLICY "Allow anon all on customers" ON public.customers FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon all on transactions" ON public.transactions;
CREATE POLICY "Allow anon all on transactions" ON public.transactions FOR ALL TO anon USING (true) WITH CHECK (true);
